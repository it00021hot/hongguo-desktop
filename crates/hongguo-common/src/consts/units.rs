//! 通用时间 / 体积换算。
//!
//! 只放「任何域都成立」的换算基准；带业务语义的阈值（播放器窗口、各类超时秒数）属于它们各自的域，不要搬进来。

/// 1 秒 = 1000 毫秒。配合 i64 时间戳参与有符号运算。
pub const MS_PER_SEC: i64 = 1_000;

/// 1 小时 = 3_600_000 毫秒。
pub const MS_PER_HOUR: i64 = 3_600 * MS_PER_SEC;

/// 1 天 = 86_400_000 毫秒。
pub const MS_PER_DAY: i64 = 24 * MS_PER_HOUR;

/// 最小有效媒体文件（100 KiB）：小于此视为半成品/损坏——下载扫描与转码缓存命中共用。
pub const MIN_MEDIA_BYTES: u64 = 100 * 1024;
